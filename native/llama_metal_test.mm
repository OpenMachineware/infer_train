// llama.cpp Metal MV test - Direct Metal API call
// Compile: clang++ -O2 -framework Metal -framework Foundation -o llama_metal_test llama_metal_test.mm

#import <Metal/Metal.h>
#import <Foundation/Foundation.h>
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#define QK_K 256

typedef struct {
    uint8_t scales[12];
    uint8_t qs[128];
    uint16_t d;
    uint16_t dmin;
} __attribute__((packed)) block_q4_K;

// Args structure matching llama.cpp
typedef struct {
    int32_t ne00; int32_t ne01; uint64_t nb00; uint64_t nb01; uint64_t nb02; uint64_t nb03;
    int32_t ne10; int32_t ne11; int32_t ne12; uint64_t nb10; uint64_t nb11; uint64_t nb12; uint64_t nb13;
    int32_t ne0; int32_t ne1; int32_t nr0; int16_t r2; int16_t r3;
} __attribute__((packed)) mv_args;

uint64_t get_time_ns(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec * 1000000000ULL + ts.tv_nsec;
}

int main() {
    @autoreleasepool {
        printf("llama.cpp Metal MV Test - Q4_K (Direct Metal API)\n");
        printf("=================================================\n\n");

        // Create Metal device
        id<MTLDevice> device = MTLCreateSystemDefaultDevice();
        if (!device) {
            printf("Error: No Metal device found\n");
            return 1;
        }
        printf("Metal device: %s\n", device.name.UTF8String);

        // Load Metal library from llama.cpp (preprocessed with all includes)
        NSString* shaderPath = @"../llama.cpp-0.5.0/build-metal/ggml/src/ggml-metal/autogenerated/ggml-metal-embed-mul_mv.metal";
        NSError* readError = nil;
        NSString* shaderSource = [NSString stringWithContentsOfFile:shaderPath encoding:NSUTF8StringEncoding error:&readError];
        if (!shaderSource) {
            printf("Error: Could not load Metal shader from %s: %s\n", shaderPath.UTF8String, readError.localizedDescription.UTF8String);
            return 1;
        }
        printf("Loaded shader: %lu bytes\n", (unsigned long)shaderSource.length);

        NSError* error = nil;
        id<MTLLibrary> library = [device newLibraryWithSource:shaderSource options:nil error:&error];
        if (!library) {
            printf("Error: Failed to compile Metal library: %s\n", error.localizedDescription.UTF8String);
            return 1;
        }

        // Get kernel function
        id<MTLFunction> kernel = [library newFunctionWithName:@"kernel_mul_mv_q4_K_f32"];
        if (!kernel) {
            printf("Error: Could not find kernel function\n");
            return 1;
        }

        // Create pipeline
        id<MTLComputePipelineState> pipeline = [device newComputePipelineStateWithFunction:kernel error:&error];
        if (!pipeline) {
            printf("Error: Failed to create pipeline: %s\n", error.localizedDescription.UTF8String);
            return 1;
        }
        printf("Pipeline created: %lu threads per threadgroup\n", (unsigned long)pipeline.maxTotalThreadsPerThreadgroup);

        // Test parameters
        const int m = 4096;
        const int k = 4096;
        const int nb = m * (k / QK_K);
        const int seed = 42;

        // Generate test data
        block_q4_K* weights = (block_q4_K*)malloc(nb * sizeof(block_q4_K));
        for (int i = 0; i < nb; i++) {
            weights[i].d = 15360;
            weights[i].dmin = 0;
            for (int j = 0; j < 12; j++) weights[i].scales[j] = ((j + 1) % 4) + 1;
            for (int j = 0; j < 128; j++) weights[i].qs[j] = ((i + j + seed) & 0xFF);
        }

        float* input = (float*)malloc(k * sizeof(float));
        for (int i = 0; i < k; i++) input[i] = 1.0f;

        float* output = (float*)malloc(m * sizeof(float));

        // Create Metal buffers
        id<MTLBuffer> weightsBuffer = [device newBufferWithBytes:weights length:nb * sizeof(block_q4_K) options:MTLResourceStorageModeShared];
        id<MTLBuffer> inputBuffer = [device newBufferWithBytes:input length:k * sizeof(float) options:MTLResourceStorageModeShared];
        id<MTLBuffer> outputBuffer = [device newBufferWithLength:m * sizeof(float) options:MTLResourceStorageModeShared];
        id<MTLBuffer> argsBuffer = [device newBufferWithLength:sizeof(mv_args) options:MTLResourceStorageModeShared];

        // Set args
        mv_args* args = (mv_args*)argsBuffer.contents;
        args->ne00 = k; args->ne01 = m; args->nb00 = sizeof(block_q4_K); args->nb01 = sizeof(block_q4_K); args->nb02 = 0; args->nb03 = 0;
        args->ne10 = k; args->ne11 = 1; args->ne12 = 1; args->nb10 = 4; args->nb11 = k * 4; args->nb12 = 0; args->nb13 = 0;
        args->ne0 = m; args->ne1 = 1; args->nr0 = 2; args->r2 = 1; args->r3 = 1;

        // Create command queue
        id<MTLCommandQueue> queue = [device newCommandQueue];

        // Run 10 times
        printf("\nRunning benchmark...\n");
        double total_ns = 0;
        for (int i = 0; i < 10; i++) {
            id<MTLCommandBuffer> cmdBuffer = [queue commandBuffer];
            id<MTLComputeCommandEncoder> encoder = [cmdBuffer computeCommandEncoder];

            [encoder setComputePipelineState:pipeline];
            [encoder setBuffer:argsBuffer offset:0 atIndex:0];
            [encoder setBuffer:weightsBuffer offset:0 atIndex:1];
            [encoder setBuffer:inputBuffer offset:0 atIndex:2];
            [encoder setBuffer:outputBuffer offset:0 atIndex:3];

            // Threadgroup size (from llama.cpp)
            NSUInteger tgSize = 64;
            NSUInteger tgCount = (m + 63) / 64;
            [encoder dispatchThreadgroups:MTLSizeMake(tgCount, 1, 1) threadsPerThreadgroup:MTLSizeMake(tgSize, 1, 1)];
            [encoder endEncoding];

            uint64_t start = get_time_ns();
            [cmdBuffer commit];
            [cmdBuffer waitUntilCompleted];
            uint64_t end = get_time_ns();
            total_ns += (end - start);
        }

        double avg_ns = total_ns / 10.0;
        double gflops = 2.0 * m * k / (avg_ns / 1e9) / 1e9;
        printf("\nllama.cpp Metal Q4_K MV M=4096 K=4096: %.2f GFLOPS (avg %.2f ms)\n", gflops, avg_ns / 1e6);

        // Cleanup
        free(weights);
        free(input);
        free(output);
    }
    return 0;
}
